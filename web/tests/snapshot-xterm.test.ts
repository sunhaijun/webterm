/**
 * UT-snapshot-xterm: snapshots are screen-identical (AC-2.21, ADR-0026 §10).
 *
 * xterm.js (@xterm/headless 5.5 + unicode11) is the judge:
 *
 *   reference: one xterm eats the whole recording and captures a cell grid at each cut k;
 *   candidate: a fresh xterm follows the browser path, first eating the agent's snapshot at
 *              k (RIS + streaming decode), compared with the reference at k (the handover
 *              moment); then it eats the bytes after k and is compared at the end.
 *
 * Compares every cell's character, width, colors and attributes, plus cursor, cursor
 * visibility, terminal modes and whether the alternate screen is active. The main screen
 * is aligned from the bottom up (snapshots carry at most 2000 lines of history, so extra
 * lines at the top of the reference are not errors).
 *
 * Only the known differences listed in ADR-0026 are allowed:
 *   - soft-wrap markers (xterm marks the next line, tuios the previous one; only visible on reflow);
 *   - the last cell of a row: after a program fills a row and sends EL, xterm.js doesn't
 *     erase the last cell (top's header loses its reverse video there);
 *   - SGR 53 (overline) is dropped by snapshots;
 *   - how the cursor is recorded in the last column with autowrap off (x = cols vs cols-1).
 *
 * Recordings live in internal/vterm/testdata/rec/<name>.bin|json; the golden snapshots
 * at each cut are generated by the Go side into internal/vterm/testdata/snap/<name>.<k>.snap
 * and snap/cuts.json. WEBTERM_SNAP_DIR can point the golden directory elsewhere (for
 * offline experiments).
 *
 * Missing goldens fail the test instead of skipping it; skipping would be a false green.
 */
import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { join, resolve } from 'node:path'

import headless from '@xterm/headless'
import { Unicode11Addon } from '@xterm/addon-unicode11'
import { describe, expect, it } from 'vitest'

import { RIS } from '../src/term/terminal'

const { Terminal } = headless
type HTerm = InstanceType<typeof Terminal>

const REC_DIR = resolve(process.cwd(), '../internal/vterm/testdata/rec')
const SNAP_DIR = process.env.WEBTERM_SNAP_DIR
  ? resolve(process.env.WEBTERM_SNAP_DIR)
  : resolve(process.cwd(), '../internal/vterm/testdata/snap')
const CUTS = join(SNAP_DIR, 'cuts.json')

interface Meta {
  name: string
  cols: number
  rows: number
}

/** Like the browser: one streaming UTF-8 decoder per terminal, decode to a string before writing. */
interface Judge {
  t: HTerm
  dec: TextDecoder
}

function mk(cols: number, rows: number): Judge {
  const t = new Terminal({ cols, rows, scrollback: 5000, allowProposedApi: true })
  t.loadAddon(new Unicode11Addon() as unknown as Parameters<HTerm['loadAddon']>[0])
  t.unicode.activeVersion = '11'
  return { t, dec: new TextDecoder('utf-8') }
}

const write = (j: Judge, s: string) => new Promise<void>((r) => j.t.write(s, () => r()))
const feed = (j: Judge, b: Uint8Array) => write(j, j.dec.decode(b, { stream: true }))
/** The browser receiving a snapshot: RIS (in-stream reset) → fresh decoder → write the snapshot. */
const feedSnapshot = (j: Judge, b: Uint8Array) => {
  j.dec = new TextDecoder('utf-8')
  return write(j, RIS + j.dec.decode(b, { stream: true }))
}

// ---------- Cell grid ----------

/** Palette colors: 31m (P16) and 38;5;1m (P256) look the same, so treat them as one. */
const colorMode = (mode: number) => (mode === 0 ? 'd' : mode === 0x3000000 ? 'r' : 'p')

type Cell = NonNullable<ReturnType<NonNullable<ReturnType<HTerm['buffer']['active']['getLine']>>['getCell']>>

/** A cell = char | width | fg | bg | 9 attribute bits (bold italic dim underline blink inverse invisible strikethrough overline). */
function cellKey(c: Cell): string {
  const ch = c.getChars() || ' '
  const flags = [c.isBold(), c.isItalic(), c.isDim(), c.isUnderline(), c.isBlink(), c.isInverse(), c.isInvisible(), c.isStrikethrough(), c.isOverline()]
    .map((v) => (v ? 1 : 0))
    .join('')
  // A space's foreground is invisible (absent inverse / underline / strikethrough / overline), so normalize it
  const blankInk = ch === ' ' && !c.isInverse() && !c.isUnderline() && !c.isStrikethrough() && !c.isOverline()
  const fg = blankInk || c.isFgDefault() ? 'd' : colorMode(c.getFgColorMode()) + c.getFgColor()
  const bg = c.isBgDefault() ? 'd' : colorMode(c.getBgColorMode()) + c.getBgColor()
  return `${ch}|${c.getWidth()}|${fg}|${bg}|${flags}`
}

interface Line {
  wrapped: boolean
  cells: string[]
  text: string
}

interface Grid {
  type: string
  cx: number
  cy: number
  hidden: boolean | null
  modes: Record<string, unknown>
  normal: Line[]
  alt: Line[]
}

function lineOf(buf: HTerm['buffer']['normal'], y: number, cols: number): Line {
  const line = buf.getLine(y)!
  const cells: string[] = []
  for (let x = 0; x < cols; x++) cells.push(cellKey(line.getCell(x)!))
  return { wrapped: line.isWrapped, cells, text: line.translateToString(true) }
}

function grid(t: HTerm): Grid {
  const a = t.buffer.active
  const modes: Record<string, unknown> = {}
  const m = t.modes as unknown as Record<string, unknown>
  for (const k of Object.keys(m)) modes[k] = m[k]
  const g: Grid = {
    type: a.type,
    cx: a.cursorX,
    cy: a.cursorY,
    hidden: (t as unknown as { _core?: { coreService?: { isCursorHidden?: boolean } } })._core?.coreService?.isCursorHidden ?? null,
    modes,
    normal: [],
    alt: [],
  }
  const n = t.buffer.normal
  for (let y = 0; y < n.length; y++) g.normal.push(lineOf(n, y, t.cols))
  if (a.type === 'alternate') {
    const al = t.buffer.alternate
    for (let y = 0; y < al.length; y++) g.alt.push(lineOf(al, y, t.cols))
  }
  return g
}

// ---------- Comparison ----------

interface Diff {
  what: string
  /** null = an unexplained difference; otherwise the name of an allowed known difference. */
  allowed: string | null
  detail: string
}

/** Differs only in the overline bit. */
function overlineOnly(r: string, c: string): boolean {
  const a = r.split('|')
  const b = c.split('|')
  if (a.slice(0, 4).join('|') !== b.slice(0, 4).join('|')) return false
  const fa = a[4]!
  const fb = b[4]!
  return fa.slice(0, 8) === fb.slice(0, 8) && fa[8] !== fb[8]
}

/** Same character and width (differs only in color or attributes). */
function sameGlyph(r: string, c: string): boolean {
  const a = r.split('|')
  const b = c.split('|')
  return a[0] === b[0] && a[1] === b[1]
}

function compare(ref: Grid, cli: Grid, cols: number): Diff[] {
  const out: Diff[] = []
  if (ref.type !== cli.type) out.push({ what: 'buffer', allowed: null, detail: `${ref.type} / ${cli.type}` })
  if (ref.cx !== cli.cx || ref.cy !== cli.cy) {
    const xs = [ref.cx, cli.cx].sort((x, y) => x - y)
    const autowrapOff = ref.modes.wraparoundMode === false
    const allowed = ref.cy === cli.cy && autowrapOff && xs[0] === cols - 1 && xs[1] === cols ? 'cursor x with autowrap off' : null
    out.push({ what: 'cursor', allowed, detail: `reference (${ref.cx},${ref.cy}) / snapshot (${cli.cx},${cli.cy})` })
  }
  if (ref.hidden !== cli.hidden) out.push({ what: 'cursor-hidden', allowed: null, detail: `${ref.hidden} / ${cli.hidden}` })
  for (const k of Object.keys(ref.modes)) {
    if (ref.modes[k] !== cli.modes[k]) out.push({ what: `mode:${k}`, allowed: null, detail: `${String(ref.modes[k])} / ${String(cli.modes[k])}` })
  }
  for (const which of ref.type === 'alternate' ? (['normal', 'alt'] as const) : (['normal'] as const)) {
    const R = ref[which]
    const C = cli[which]
    const n = Math.min(R.length, C.length)
    for (let i = 1; i <= n; i++) {
      const r = R[R.length - i]!
      const c = C[C.length - i]!
      // The top row's soft-wrap marker depends on whether history above it was cut off; skip it
      if (i < n && r.wrapped !== c.wrapped) {
        out.push({ what: `${which}:wrap`, allowed: 'soft-wrap marker', detail: `row ${i} from bottom "${r.text}"` })
      }
      for (let x = 0; x < cols; x++) {
        const rc = r.cells[x]!
        const cc = c.cells[x]!
        if (rc === cc) continue
        const allowed = overlineOnly(rc, cc)
          ? 'SGR 53 overline'
          : x === cols - 1 && sameGlyph(rc, cc)
            ? 'last cell of row (not erased by EL)'
            : null
        out.push({
          what: `${which}:cell`,
          allowed,
          detail: `row ${i} from bottom x=${x}: reference ${rc} / snapshot ${cc}\n    reference "${r.text}"\n    snapshot  "${c.text}"`,
        })
      }
    }
  }
  return out
}

// ---------- Goldens ----------

function recordings(): Meta[] {
  if (!existsSync(REC_DIR)) return []
  return readdirSync(REC_DIR)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => JSON.parse(readFileSync(join(REC_DIR, f), 'utf8')) as Meta)
}

/** cuts.json: `{ <name>: [{ k, ... }] }` (`{ <name>: [k, ...] }` is accepted too). */
function cutsOf(all: Record<string, unknown>, name: string): number[] | null {
  const v = all[name]
  if (!Array.isArray(v)) return null
  return v.map((x) => (typeof x === 'number' ? x : (x as { k: number }).k)).sort((a, b) => a - b)
}

const recs = recordings()
const golden = existsSync(CUTS)
const allCuts: Record<string, unknown> = golden ? JSON.parse(readFileSync(CUTS, 'utf8')) : {}

describe('UT-snapshot-xterm snapshots are screen-identical (AC-2.21)', () => {
  it('has recordings and goldens', () => {
    expect(recs.length, `missing recordings: no *.json in ${REC_DIR}`).toBeGreaterThan(0)
    expect(
      golden,
      `missing goldens: ${CUTS} does not exist; run the Go side first to generate snapshots at each cut (UT-vterm-golden in internal/vterm)`,
    ).toBe(true)
  })

  for (const m of recs) {
    it(
      m.name,
      async () => {
        expect(golden, `missing goldens: ${CUTS} does not exist`).toBe(true)
        const cuts = cutsOf(allCuts, m.name)
        expect(cuts, `missing goldens: ${m.name} not in cuts.json`).not.toBeNull()
        const missing = cuts!.map((k) => join(SNAP_DIR, `${m.name}.${k}.snap`)).filter((f) => !existsSync(f))
        expect(missing, `missing goldens: ${missing.slice(0, 3).join(', ')}`).toEqual([])

        const bytes = new Uint8Array(readFileSync(join(REC_DIR, `${m.name}.bin`)))
        // Reference: feed in order, capturing at each cut
        const ref = mk(m.cols, m.rows)
        const refAt = new Map<number, Grid>()
        let prev = 0
        for (const k of cuts!) {
          await feed(ref, bytes.subarray(prev, k))
          prev = k
          refAt.set(k, grid(ref.t))
        }
        await feed(ref, bytes.subarray(prev))
        const refEnd = grid(ref.t)
        ref.t.dispose()

        const bad: string[] = []
        const allowed: Record<string, number> = {}
        const tally = (k: number, phase: string, diffs: Diff[]) => {
          for (const d of diffs) {
            if (d.allowed) allowed[d.allowed] = (allowed[d.allowed] ?? 0) + 1
            else if (bad.length < 8) bad.push(`k=${k} (${phase}) ${d.what}: ${d.detail}`)
            else bad.push('…')
          }
        }
        for (const k of cuts!) {
          const snap = new Uint8Array(readFileSync(join(SNAP_DIR, `${m.name}.${k}.snap`)))
          const cli = mk(m.cols, m.rows)
          await feedSnapshot(cli, snap)
          tally(k, 'at handover', compare(refAt.get(k)!, grid(cli.t), m.cols))
          if (k < bytes.length) {
            await feed(cli, bytes.subarray(k))
            tally(k, 'at end', compare(refEnd, grid(cli.t), m.cols))
          }
          cli.t.dispose()
        }
        if (Object.keys(allowed).length) console.info(`${m.name}: known differences ${JSON.stringify(allowed)}`)
        expect(bad, `${m.name} has unexplained differences:\n${bad.join('\n')}`).toEqual([])
      },
      120_000,
    )
  }
})
