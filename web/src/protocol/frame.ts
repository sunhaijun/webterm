/**
 * Binary data frame encoding and decoding (protocol §3, v2).
 *
 * The contract is docs/30-protocol/websocket-protocol.md. This side must match the Go
 * side's internal/protocol exactly; both run testdata/vectors.json.
 */

export const PROTOCOL_VERSION = 2

export const HEADER_SIZE = 12
export const MAX_PAYLOAD = 256 * 1024

export const TYPE_OUTPUT = 0x01 // agent → client
export const TYPE_INPUT = 0x02 // client → agent
export const TYPE_SNAPSHOT = 0x03 // agent → client

/**
 * SNAPSHOT flags bit0: more frames of the same snapshot follow (§3). All other bits, and
 * bit0 on other frame types, are reserved: senders set 0, receivers ignore them.
 */
export const FLAG_MORE = 0x01

export interface Frame {
  type: number
  flags: number
  sid: number
  /** OUTPUT / INPUT: seq of the frame's first byte. SNAPSHOT: the out_seq the snapshot corresponds to. */
  seq: bigint
  payload: Uint8Array
}

export class BadFrameError extends Error {
  constructor(msg = 'bad frame') {
    super(msg)
    this.name = 'BadFrameError'
  }
}

export class FrameTooLargeError extends Error {
  constructor(msg = 'frame too large') {
    super(msg)
    this.name = 'FrameTooLargeError'
  }
}

export function encodeFrame(f: Frame): Uint8Array {
  const out = new Uint8Array(HEADER_SIZE + f.payload.length)
  const view = new DataView(out.buffer)
  view.setUint8(0, f.type)
  view.setUint8(1, f.flags)
  view.setUint16(2, f.sid, false) // big-endian
  view.setBigUint64(4, f.seq, false)
  out.set(f.payload, HEADER_SIZE)
  return out
}

/**
 * Decodes one frame. Validates only the frame itself (length, type); direction (the agent
 * must not send INPUT) is checked by the receiver.
 */
export function decodeFrame(b: Uint8Array): Frame {
  // A frame with an empty payload is invalid
  if (b.length < HEADER_SIZE + 1) throw new BadFrameError('frame too short')
  if (b.length - HEADER_SIZE > MAX_PAYLOAD) throw new FrameTooLargeError()

  const view = new DataView(b.buffer, b.byteOffset, b.byteLength)
  const f: Frame = {
    type: view.getUint8(0),
    flags: view.getUint8(1),
    sid: view.getUint16(2, false),
    seq: view.getBigUint64(4, false),
    payload: b.subarray(HEADER_SIZE),
  }
  if (f.type !== TYPE_OUTPUT && f.type !== TYPE_INPUT && f.type !== TYPE_SNAPSHOT) {
    throw new BadFrameError(`unknown frame type ${f.type}`)
  }
  return f
}

/**
 * Bytes this frame contributes to seq: the payload length for OUTPUT / INPUT, 0 for
 * SNAPSHOT. A snapshot is a rendering instruction generated by the agent, not stream
 * content (§3, invariant 4).
 *
 * Consecutive OUTPUT frames must satisfy seq(n+1) === seq(n) + dataLen(n).
 */
export function dataLen(f: Frame): number {
  return f.type === TYPE_SNAPSHOT ? 0 : f.payload.length
}

/** Whether more frames of the same snapshot follow (meaningful for SNAPSHOT only; bit0 is reserved on other types). */
export function hasMore(f: Frame): boolean {
  return f.type === TYPE_SNAPSHOT && (f.flags & FLAG_MORE) !== 0
}
