package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// install-state holds one argument per line and is replayed verbatim; that is
// why it is not key=value. Pin down that what is read back matches what was
// written, with comments and blank lines skipped.
func TestReadInstallState(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "install-state")
	content := `# Generated by scripts/install.sh.
# One argument per line.

--domain
term.example.com
--https-port
8443
--channel
dev
`
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
	got, err := readInstallState(path)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"--domain", "term.example.com", "--https-port", "8443", "--channel", "dev"}
	if strings.Join(got, "\x00") != strings.Join(want, "\x00") {
		t.Errorf("read back %q, want %q", got, want)
	}
}

// Values with spaces survive intact; that is the point of one argument per line.
func TestReadInstallStateKeepsSpaces(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "install-state")
	if err := os.WriteFile(path, []byte("--prefix\n/opt/my apps/bin\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	got, err := readInstallState(path)
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 2 || got[1] != "/opt/my apps/bin" {
		t.Errorf("value with spaces was split: %q", got)
	}
}

// Without a prior install, the error says what to do, not just "no such file".
func TestReadInstallStateMissing(t *testing.T) {
	_, err := readInstallState(filepath.Join(t.TempDir(), "nope"))
	if err == nil {
		t.Fatal("missing file was not an error")
	}
	for _, want := range []string{"not been installed with install.sh", "install.md"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("error is missing %q: %v", want, err)
		}
	}
}

// A file with only comments has no arguments; never rerun the install with none.
func TestReadInstallStateEmpty(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "install-state")
	if err := os.WriteFile(path, []byte("# comments only\n\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := readInstallState(path); err == nil {
		t.Error("empty arguments were not an error")
	}
}

// install-state sits next to config; both belong in the XDG config directory.
func TestInstallStatePathSitsBesideConfig(t *testing.T) {
	t.Setenv("XDG_CONFIG_HOME", "/x/cfg")
	if got, want := installStatePath(), "/x/cfg/webterm/install-state"; got != want {
		t.Errorf("installStatePath() = %q, want %q", got, want)
	}
	if filepath.Dir(installStatePath()) != filepath.Dir(defaultConfigPath()) {
		t.Errorf("install-state and config are in different directories: %q vs %q",
			installStatePath(), defaultConfigPath())
	}
}
